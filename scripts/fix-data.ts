// COMMAND: io-categories
// =============================================================================

function fixIOCategories(dryRun: boolean): number {
  let totalChanges = 0;
  const digitalTypes = new Set(["s/pdif", "adat", "aes/ebu", "word clock", "dante"]);
  const files = getAllDataFiles(["hardware"]);

  for (const file of files) {
    const content = fs.readFileSync(file, "utf-8");
    const doc = parseDocument(content);
    let changed = false;

    const ioNode = doc.get("io");
    if (isSeq(ioNode)) {
      for (let i = 0; i < ioNode.items.length; i++) {
        const ioMap = ioNode.items[i];
        if (isMap(ioMap)) {
          const data = ioMap.toJSON() as Record<string, unknown>;
          const ioType = data.type as string | undefined;
          const ioCat = data.category as string | undefined;

          if (ioType && digitalTypes.has(ioType) && ioCat === "audio") {
            // Find the category pair and update it
            for (const pair of ioMap.items) {
              if (isPair(pair) && (pair.key as Scalar)?.value === "category") {
                (pair.value as Scalar).value = "digital";
                const name = data.name || `io[${i}]`;
                console.log(
                  `  ${relPath(file)}: ${name} category 'audio' → 'digital' (type: ${ioType})`
                );
                changed = true;
                break;
              }
            }
          }
        }
      }
    }

    if (changed) {
      totalChanges++;
      if (!dryRun) {
        fs.writeFileSync(file, doc.toString());
      }
    }
  }

  return totalChanges;
}

