// COMMAND: extract-formats
// =============================================================================

// Category values that are actually plugin formats
const FORMAT_CATEGORY_MAP: Record<string, string> = {
  "audio-unit": "au",
  vst3: "vst3",
  aax: "aax",
  lv2: "lv2",
  "rack-extension": "rack-extension",
  "pro-tools": "aax",
  "pro-tools-plugin": "aax",
};

// Category values that are actually host/DAW references
const HOST_CATEGORY_MAP: Record<string, string> = {
  "ableton-live": "ableton-live",
  ableton: "ableton-live",
  kontakt: "kontakt",
};

function extractFormats(dryRun: boolean): number {
  let totalChanges = 0;
  const files = getAllDataFiles(["software"]);

  for (const file of files) {
    const content = fs.readFileSync(file, "utf-8");
    const doc = parseDocument(content);
    const data = doc.toJSON() as Record<string, unknown>;
    let changed = false;

    const formatsToAdd = new Set<string>();
    const hostsToAdd = new Set<string>();
    const indicesToRemove: number[] = [];

    // Check primaryCategory for format/host misuse
    const pc = data.primaryCategory as string | undefined;
    if (pc && FORMAT_CATEGORY_MAP[pc]) {
      formatsToAdd.add(FORMAT_CATEGORY_MAP[pc]);
      // Replace primaryCategory with 'plugin' since we can't leave it empty
      doc.set("primaryCategory", "plugin");
      console.log(
        `  ${relPath(file)}: primaryCategory '${pc}' → 'plugin' (extracted format '${FORMAT_CATEGORY_MAP[pc]}')`
      );
      changed = true;
    } else if (pc && HOST_CATEGORY_MAP[pc]) {
      hostsToAdd.add(HOST_CATEGORY_MAP[pc]);
      doc.set("primaryCategory", "plugin");
      console.log(
        `  ${relPath(file)}: primaryCategory '${pc}' → 'plugin' (extracted host '${HOST_CATEGORY_MAP[pc]}')`
      );
      changed = true;
    }

    // Scan categories array for format/host values
    const categoriesNode = doc.get("categories");
    if (isSeq(categoriesNode)) {
      for (let i = 0; i < categoriesNode.items.length; i++) {
        const item = categoriesNode.items[i];
        const val =
          typeof item === "object" && item !== null && "value" in item
            ? (item as Scalar).value
            : item;
        if (typeof val !== "string") continue;

        if (FORMAT_CATEGORY_MAP[val]) {
          formatsToAdd.add(FORMAT_CATEGORY_MAP[val]);
          indicesToRemove.push(i);
          console.log(
            `  ${relPath(file)}: categories[${i}] '${val}' → formats '${FORMAT_CATEGORY_MAP[val]}'`
          );
          changed = true;
        } else if (HOST_CATEGORY_MAP[val]) {
          hostsToAdd.add(HOST_CATEGORY_MAP[val]);
          indicesToRemove.push(i);
          console.log(
            `  ${relPath(file)}: categories[${i}] '${val}' → compatibleWith '${HOST_CATEGORY_MAP[val]}'`
          );
          changed = true;
        }
      }

      // Remove extracted items in reverse order
      for (const idx of indicesToRemove.sort((a, b) => b - a)) {
        categoriesNode.items.splice(idx, 1);
      }

      // Remove empty categories array
      if (categoriesNode.items.length === 0) {
        doc.delete("categories");
      }
    }

    // Merge extracted formats into existing formats array
    if (formatsToAdd.size > 0) {
      const existing = (doc.toJSON() as Record<string, unknown>).formats as string[] | undefined;
      const merged = new Set(existing ?? []);
      for (const f of formatsToAdd) merged.add(f);
      const formatsArr = new YAMLSeq();
      for (const f of merged) formatsArr.add(f);
      doc.set("formats", formatsArr);
    }

    // Merge extracted hosts into existing compatibleWith array
    if (hostsToAdd.size > 0) {
      const existing = (doc.toJSON() as Record<string, unknown>).compatibleWith as
        | string[]
        | undefined;
      const merged = new Set(existing ?? []);
      for (const h of hostsToAdd) merged.add(h);
      const hostsArr = new YAMLSeq();
      for (const h of merged) hostsArr.add(h);
      doc.set("compatibleWith", hostsArr);
    }

    if (changed) {
      totalChanges++;
      if (!dryRun) {
        fs.writeFileSync(file, doc.toString());
      }
    }
  }

  return totalChanges;
}

