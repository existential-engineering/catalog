// COMMAND: videos
// =============================================================================

function fixVideos(dryRun: boolean): number {
  let totalChanges = 0;
  const files = getAllDataFiles(["software", "content", "hardware", "accessories"]);

  for (const file of files) {
    const content = fs.readFileSync(file, "utf-8");
    const doc = parseDocument(content);
    let changed = false;

    const videosNode = doc.get("videos");
    if (isSeq(videosNode)) {
      for (let i = 0; i < videosNode.items.length; i++) {
        const videoMap = videosNode.items[i];
        if (isMap(videoMap)) {
          const providerPair = videoMap.items.find(
            (p) => isPair(p) && (p.key as Scalar)?.value === "provider"
          );
          if (providerPair && isPair(providerPair)) {
            const providerVal = (providerPair.value as Scalar)?.value;
            if (providerVal === "youtube") {
              videoMap.items = videoMap.items.filter(
                (p) => !(isPair(p) && (p.key as Scalar)?.value === "provider")
              );
              console.log(`  ${relPath(file)}: videos[${i}] removed redundant provider: youtube`);
              changed = true;
            }
          }
        }
      }
    }

    if (changed) {
      totalChanges++;
      if (!dryRun) {
        fs.writeFileSync(file, doc.toString());
      }
    }
  }

  return totalChanges;
}

