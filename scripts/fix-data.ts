// =============================================================================
// HELPERS
// =============================================================================

function getYamlFiles(dir: string): string[] {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".yaml") || f.endsWith(".yml"))
    .map((f) => path.join(dir, f));
}

function getAllDataFiles(collections?: string[]): string[] {
  const dirs = collections ?? ["manufacturers", "software", "content", "hardware", "accessories"];
  return dirs.flatMap((c) => getYamlFiles(path.join(DATA_DIR, c)));
}

function relPath(file: string): string {
  return path.relative(REPO_ROOT, file);
}

// =============================================================================
// COMMAND: categories
// =============================================================================

function fixCategories(dryRun: boolean): number {
  const schema = loadSchemaContext();
  const validCategories = new Set(schema.categories);
  const aliasMap = schema.categoryAliases;
  let totalChanges = 0;

  const files = getAllDataFiles(["software", "content", "hardware", "accessories"]);

  for (const file of files) {
    const content = fs.readFileSync(file, "utf-8");
    const doc = parseDocument(content);
    const data = doc.toJSON() as Record<string, unknown>;
    let changed = false;

    // Fix primaryCategory
    if (typeof data.primaryCategory === "string") {
      const pc = data.primaryCategory;
      if (!validCategories.has(pc) && !aliasMap[pc]) {
        if (CATEGORY_MAP[pc]) {
          console.log(`  ${relPath(file)}: primaryCategory '${pc}' → '${CATEGORY_MAP[pc]}'`);
          doc.set("primaryCategory", CATEGORY_MAP[pc]);
          changed = true;
        } else if (CATEGORIES_TO_REMOVE.has(pc)) {
          console.log(`  ${relPath(file)}: primaryCategory '${pc}' → removing (unmappable)`);
          // Can't remove primaryCategory (required) — set to 'other'
          doc.set("primaryCategory", "other");
          changed = true;
        } else {
          console.log(`  ⚠ ${relPath(file)}: primaryCategory '${pc}' — NO MAPPING FOUND`);
        }
      }
    }

    // Fix categories array
    const categoriesNode = doc.get("categories");
    if (isSeq(categoriesNode)) {
      const updatedPrimary = (doc.toJSON() as Record<string, unknown>).primaryCategory as string;
      const secondaryCategory = data.secondaryCategory as string | undefined;
      const seen = new Set<string>();
      const toRemoveIndices: number[] = [];

      for (let i = 0; i < categoriesNode.items.length; i++) {
        const item = categoriesNode.items[i];
        const val =
          typeof item === "object" && item !== null && "value" in item
            ? (item as Scalar).value
            : item;
        if (typeof val !== "string") continue;

        let finalVal = val;

        // Remap invalid categories
        if (!validCategories.has(val) && !aliasMap[val]) {
          if (CATEGORY_MAP[val]) {
            finalVal = CATEGORY_MAP[val];
            console.log(`  ${relPath(file)}: categories[${i}] '${val}' → '${finalVal}'`);
            categoriesNode.set(i, finalVal);
            changed = true;
          } else if (CATEGORIES_TO_REMOVE.has(val)) {
            toRemoveIndices.push(i);
            console.log(`  ${relPath(file)}: categories[${i}] '${val}' → removed`);
            changed = true;
            continue;
          } else {
            console.log(`  ⚠ ${relPath(file)}: categories[${i}] '${val}' — NO MAPPING FOUND`);
            continue;
          }
        }

        // Track for dedup
        if (finalVal === updatedPrimary || finalVal === secondaryCategory || seen.has(finalVal)) {
          toRemoveIndices.push(i);
          if (finalVal === updatedPrimary) {
            console.log(
              `  ${relPath(file)}: categories[${i}] '${finalVal}' → removed (duplicate of primaryCategory)`
            );
          } else if (finalVal === secondaryCategory) {
            console.log(
              `  ${relPath(file)}: categories[${i}] '${finalVal}' → removed (duplicate of secondaryCategory)`
            );
          } else {
            console.log(`  ${relPath(file)}: categories[${i}] '${finalVal}' → removed (duplicate)`);
          }
          changed = true;
          continue;
        }
        seen.add(finalVal);
      }

      // Remove items in reverse order to preserve indices
      for (const idx of toRemoveIndices.sort((a, b) => b - a)) {
        categoriesNode.items.splice(idx, 1);
      }

      // Remove empty categories array
      if (categoriesNode.items.length === 0) {
        doc.delete("categories");
        console.log(`  ${relPath(file)}: removed empty categories array`);
        changed = true;
      }
    }

    if (changed) {
      totalChanges++;
      if (!dryRun) {
        fs.writeFileSync(file, doc.toString());
      }
    }
  }

  return totalChanges;
}

// =============================================================================
// COMMAND: block-scalars
// =============================================================================

function fixBlockScalars(dryRun: boolean): number {
  let totalChanges = 0;
  const files = getAllDataFiles(["software", "content", "hardware", "accessories"]);

  for (const file of files) {
    const content = fs.readFileSync(file, "utf-8");
    const doc = parseDocument(content);
    let changed = false;

    // Fix details: array → block scalar
    const detailsNode = doc.get("details");
    if (isSeq(detailsNode)) {
      const items = detailsNode.items.map((item) => {
        if (typeof item === "object" && item !== null && "value" in item)
          return String((item as Scalar).value);
        return String(item);
      });
      const blockText = items.join("\n\n");
      const scalar = new Scalar(blockText);
      scalar.type = Scalar.BLOCK_LITERAL;
      doc.set("details", scalar);
      console.log(`  ${relPath(file)}: details array (${items.length} items) → block scalar`);
      changed = true;
    }

    // Fix specs: array → block scalar with "- " prefix
    const specsNode = doc.get("specs");
    if (isSeq(specsNode)) {
      const items = specsNode.items.map((item) => {
        if (typeof item === "object" && item !== null && "value" in item)
          return String((item as Scalar).value);
        return String(item);
      });
      const blockText = items.map((item) => `- ${item}`).join("\n");
      const scalar = new Scalar(blockText);
      scalar.type = Scalar.BLOCK_LITERAL;
      doc.set("specs", scalar);
      console.log(`  ${relPath(file)}: specs array (${items.length} items) → block scalar`);
      changed = true;
    }

    if (changed) {
      totalChanges++;
      if (!dryRun) {
        fs.writeFileSync(file, doc.toString());
      }
    }
  }

  return totalChanges;
}

